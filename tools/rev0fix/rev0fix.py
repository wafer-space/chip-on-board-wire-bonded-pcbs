"""Get a board through NextPCB Rev 0's hole checks in one command.

    python tools/rev0fix/rev0fix.py run-2/1x1-cob/1x1-mezzanine.kicad_pcb [--export TAG]

1. Rules: sets the via hole clearance and same-net hole-to-hole in the .kicad_pro, and writes the
   pad-hole and different-net hole-to-hole rules into the board's .kicad_dru (between markers).
2. Rounds (up to --rounds): extract geometry -> solve.py moves vias and track corners -> apply.py ->
   kicad-cli DRC with --refill-zones --save-board (this refills AND rebuilds the teardrops).
   Stops when DRC shows none of the blocking types.
3. --export TAG: Fabrication Toolkit export, trimmed to what Rev 0 accepted (no drill maps, no empty
   NPTH file), saved as production/<board>_REV0-UPLOAD_<date>_<TAG>.zip. Toolkit extras are removed.

Work files go to .rev0fix/<board>/ (gitignored).
"""
import argparse, collections, datetime, json, os, re, shutil, subprocess, sys, zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
KICAD_BIN = os.environ.get("KICAD_BIN", r"C:\Program Files\KiCad\10.0\bin")
KPY = os.path.join(KICAD_BIN, "python.exe")
KCLI = os.path.join(KICAD_BIN, "kicad-cli.exe")
EXTRACT = os.path.join(ROOT, "tools", "pcbdiff", "extract.py")
BLOCKING = {"hole_clearance", "hole_to_hole", "clearance", "connection_width", "copper_edge_clearance",
            "shorting_items", "tracks_crossing", "drill_out_of_range", "annular_width", "track_width"}
sys.stdout.reconfigure(encoding="utf-8")

ap = argparse.ArgumentParser()
ap.add_argument("board")
ap.add_argument("--via", type=float, default=0.25, help="via hole wall to other copper, mm")
ap.add_argument("--pth", type=float, default=0.31, help="pad (component) hole wall to other copper, mm")
ap.add_argument("--hh", type=float, default=0.254, help="hole to hole, same net, mm")
ap.add_argument("--hh-diff", type=float, default=0.3048, help="hole to hole, different nets, mm")
ap.add_argument("--rounds", type=int, default=4)
ap.add_argument("--export", metavar="TAG", help="export an upload zip with this tag in its name")
ap.add_argument("--reach", type=float, default=0.2, help="max move per axis per round, mm")
ap.add_argument("--near", type=float, default=0.15, help="solver watch distance beyond each aim, mm (see solve.py)")
ap.add_argument("--ignore-fp", action="append", default=[], metavar="REF",
                help="footprint (by reference) whose hole spacing is disregarded; repeatable")
ap.add_argument("--ignore-cu", type=float, default=None, metavar="MM",
                help="copper clearance to --ignore-fp footprints (default: unchanged, 0.10 mm)")
ap.add_argument("--edge", type=float, default=None, metavar="MM",
                help="copper-to-edge clearance for vias and tracks (default: the board's own). "
                     "Zones keep the board's original value through a custom rule.")
A = ap.parse_args()

board = os.path.abspath(A.board)
stem = os.path.splitext(board)[0]
name = os.path.basename(stem)
work = os.path.join(ROOT, ".rev0fix", name)
os.makedirs(work, exist_ok=True)


def run(args, **kw):
    r = subprocess.run(args, capture_output=True, text=True, encoding="utf-8", errors="replace", **kw)
    if r.returncode not in (0, 5):      # kicad-cli drc returns 5 when violations exist with --exit-code-violations
        sys.exit(f"failed: {' '.join(args)}\n{r.stdout}\n{r.stderr}")
    return r.stdout


# ---------------------------------------------------------------- 1. rules
pro = stem + ".kicad_pro"
t = open(pro, encoding="utf-8-sig").read()
t = re.sub(r'("min_hole_clearance":\s*)[\d.]+', rf"\g<1>{A.via}", t)
t = re.sub(r'("min_hole_to_hole":\s*)[\d.]+', rf"\g<1>{A.hh}", t)
edge0 = float(re.search(r'"min_copper_edge_clearance":\s*([\d.]+)', t).group(1))
GIT_EDGE = re.search(r'"min_copper_edge_clearance":\s*([\d.]+)',
                     subprocess.run(["git", "show", "HEAD:" + os.path.relpath(pro, ROOT).replace("\\", "/")],
                                    cwd=ROOT, capture_output=True, text=True).stdout or t)
zone_edge = float(GIT_EDGE.group(1)) if GIT_EDGE else edge0       # the board's own value, before any --edge run
if A.edge is not None:
    t = re.sub(r'("min_copper_edge_clearance":\s*)[\d.]+', rf"\g<1>{A.edge}", t)
if A.ignore_cu is not None:
    # Board Setup's minimum clearance is a floor that custom rules can't go under. Lower it only
    # as far as --ignore-cu; the netclass clearance (0.10) still holds everywhere else.
    i = t.index('"rules": {')
    t = t[:i] + re.sub(r'("min_clearance":\s*)[\d.]+',
                       lambda m: m.group(1) + str(min(float(m.group(0).split(":")[1]), A.ignore_cu)),
                       t[i:], count=1)
open(pro, "w", encoding="utf-8", newline="\n").write(t)

BEGIN, END = "# --- rev0fix rules (generated by tools/rev0fix/rev0fix.py) ---", "# --- end rev0fix rules ---"
block = f"""{BEGIN}
# NextPCB Rev 0 flagged pad holes at 0.233 and 0.253 mm from a trace while passing vias at 0.23 mm,
# so pad (component) holes get their own, larger hole clearance.
(rule "rev0_pad_hole_to_copper"
  (condition "(A.Type == 'Pad' && A.Pad_Type == 'Through-hole') || (B.Type == 'Pad' && B.Pad_Type == 'Through-hole')")
  (constraint hole_clearance (min {A.pth}mm)))

(rule "rev0_hole_to_hole_diff_net"
  (condition "A.NetName != B.NetName")
  (constraint hole_to_hole (min {A.hh_diff}mm)))
"""
for ref in A.ignore_fp:
    cu_note = (f"Copper clearance to it is {A.ignore_cu} mm (--ignore-cu)." if A.ignore_cu is not None
               else "Copper clearance still applies.")
    cu_line = f"\n  (constraint clearance (min {A.ignore_cu}mm))" if A.ignore_cu is not None else ""
    block += f"""
# Hole spacing on {ref} is disregarded by request (--ignore-fp {ref}). {cu_note}
(rule "rev0_ignore_{ref}"
  (condition "A.memberOfFootprint('{ref}') || B.memberOfFootprint('{ref}')")
  (constraint hole_clearance (min 0mm))
  (constraint hole_to_hole (min 0mm)){cu_line})
"""
if A.edge is not None and A.edge < zone_edge:
    block += f"""
# Vias and tracks may sit {A.edge} mm from the edge (--edge); NextPCB's V-cut limit is 0.4 mm.
# The pour keeps the board's original {zone_edge} mm, so zone outlines don't change.
(rule "rev0_zone_edge"
  (condition "A.Type == 'Zone'")
  (constraint edge_clearance (min {zone_edge}mm)))
"""
block += END + "\n"
dru = stem + ".kicad_dru"
old = open(dru, encoding="utf-8").read() if os.path.exists(dru) else "(version 1)\n"
old = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "", old, flags=re.S).rstrip() + "\n\n"
open(dru, "w", encoding="utf-8", newline="\n").write(old + block)
print(f"rules: via hole {A.via}, pad hole {A.pth}, hole-hole {A.hh} same net / {A.hh_diff} different nets (mm)"
      + (f"; hole spacing disregarded on {', '.join(A.ignore_fp)}" if A.ignore_fp else ""))


# ---------------------------------------------------------------- 2. rounds
def drc(save):
    out = os.path.join(work, "drc.json")
    args = [KCLI, "pcb", "drc", "--format", "json", "--severity-all", "--units", "mm", "--refill-zones",
            "--output", out]
    if save:
        args.append("--save-board")
    run(args + [board])
    rep = json.load(open(out, encoding="utf-8"))
    c = collections.Counter(v["type"] for v in rep["violations"])
    return c, len(rep.get("unconnected_items", [])), rep


def show(c, unc):
    blk = {k: n for k, n in c.items() if k in BLOCKING}
    other = {k: n for k, n in c.items() if k not in BLOCKING}
    print(f"    blocking: {dict(sorted(blk.items())) or 'none'}; unconnected {unc}; other: {sum(other.values())} "
          f"({', '.join(f'{k} {n}' for k, n in sorted(other.items()))})")
    return blk


c0, unc0, _ = drc(save=False)
print("DRC before:")
already_clean = not show(c0, unc0)
if already_clean:
    print("DRC already clean of blocking types; no rounds run (hand fixes stay as they are).")
for rnd in range(1, 0 if already_clean else A.rounds + 1):
    ex = os.path.join(work, f"extract_{rnd}.json")
    mv = os.path.join(work, f"moves_{rnd}.json")
    run([KPY, EXTRACT, board, ex])
    print(f"round {rnd}:")
    out = run([sys.executable, "-u", os.path.join(HERE, "solve.py"), ex, mv, "--via", str(A.via),
               "--pth", str(A.pth), "--hh", str(A.hh), "--reach", str(A.reach), "--near", str(A.near)]
              + [a for r in A.ignore_fp for a in ("--ignore-fp", r)]
              + (["--ignore-cu", str(A.ignore_cu)] if A.ignore_cu is not None else [])
              + (["--edge", str(A.edge)] if A.edge is not None else []))
    for line in out.splitlines():
        if not line.startswith("K="):
            print("    " + line)
    res = json.load(open(mv))
    if res["moves"]:
        print("    " + run([KPY, os.path.join(HERE, "apply.py"), board, mv]).strip().splitlines()[-1])
    c, unc, rep = drc(save=True)
    blk = show(c, unc)
    if unc > unc0:
        sys.exit("    STOP: new unconnected items. Check the board before going on.")
    if not blk:
        print("DRC clean of blocking types.")
        break
    if not res["moves"]:
        print("    solver has nothing left to move; remaining items need a hand fix:")
        for v in rep["violations"]:
            if v["type"] in BLOCKING:
                print(f"      {v['type']}: {v['description']} | " + " / ".join(i["description"] for i in v["items"]))
        sys.exit(1)
else:
    if not already_clean:
        sys.exit("still blocking items after the last round")

# ---------------------------------------------------------------- 3. export
if A.export:
    prod = os.path.join(os.path.dirname(board), "production")
    run([KPY, os.path.join(HERE, "export.py"), board])
    src = os.path.join(prod, name + ".zip")
    dst = os.path.join(prod, f"{name}_REV0-UPLOAD_{datetime.date.today()}_{A.export}.zip")
    zi = zipfile.ZipFile(src)
    kept = []
    with zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as z:
        for n in zi.namelist():
            data = zi.read(n)
            if "drl_map" in n:
                continue
            if n.endswith("NPTH.drl") and not re.search(rb"^X-?\d", data, re.M):
                continue
            z.writestr(zi.getinfo(n), data); kept.append(n)
    zi.close()
    for extra in (src, "bom.csv", "designators.csv", "netlist.ipc", "positions.csv", "backups"):
        p = os.path.join(prod, extra)
        if os.path.isdir(p):
            shutil.rmtree(p)
        elif os.path.exists(p):
            os.remove(p)
    print(f"upload zip: {os.path.relpath(dst, ROOT)} ({len(kept)} files)")
    for f in sorted(os.listdir(prod)):
        p = os.path.join(prod, f)
        if f.endswith(".zip") and "_REV0-UPLOAD_" in f and p != dst:
            print(f"  note: older upload zip still here: {f}")
